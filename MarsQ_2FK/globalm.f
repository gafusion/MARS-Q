C     MEAN OF (FN+FS*W)/(D0+D1*W) OVER W IN [WA,WB], W = OMEGAE0 OFFSET
C     FROM THE EVALUATION POINT.  WITH Q=FS/D1 THE QUOTIENT IS
C     Q+(FN-Q*D0)/(D0+D1*W), AND THE MEAN OF 1/(DM+D1*T), T IN [-H,H],
C     IS ATANH(E)/(E*DM), E=D1*H/DM.  IM(D) DOES NOT DEPEND ON W, SO THE
C     PRINCIPAL LOGARITHMS ARE CONTINUOUS ALONG THE SEGMENT.  SREF FIXES
C     THE SIGN OF A ZERO IMAGINARY PART: IM(D)=-NU*X**-1.5/SREF, NU->0+.
C     D1=0 (NO RESONANCE CROSSING ON THIS HALF CELL) GIVES THE EXACT
C     MEAN (FN+FS*WMID)/D0.
      PURE COMPLEX*16 FUNCTION RADLAYERMEAN(FN,FS,D0,D1,WA,WB,SREF)
      COMPLEX*16,INTENT(IN) :: FN,FS,D0
      REAL*8,INTENT(IN) :: D1,WA,WB,SREF
      COMPLEX*16 DM,ZA,ZB,E2,AVG,Q
      REAL*8 H,DI,SC

      IF (D1.EQ.0.0D0) THEN
         RADLAYERMEAN = (FN+FS*0.5D0*(WA+WB))/D0
         RETURN
      ENDIF
      H  = 0.5D0*(WB-WA)
      DM = D0+D1*0.5D0*(WA+WB)
      IF (ABS(D1*H).LE.0.1D0*ABS(DM)) THEN
         E2  = (D1*H/DM)**2
         AVG = (1.0D0+E2*(1.0D0/3.0D0+E2*(1.0D0/5.0D0+
     &         E2*(1.0D0/7.0D0+E2/9.0D0))))/DM
      ELSE
         DI = DIMAG(DM)
         SC = ABS(DREAL(DM))+ABS(D1*H)
         IF (ABS(DI).LT.1.0D-14*SC) DI = -SIGN(1.0D-14*SC,SREF)
         ZA  = DCMPLX(DREAL(DM)-D1*H,DI)
         ZB  = DCMPLX(DREAL(DM)+D1*H,DI)
         AVG = (LOG(ZB)-LOG(ZA))/(2.0D0*D1*H)
      ENDIF
      Q = FS/D1
      RADLAYERMEAN = Q+(FN+FS*0.5D0*(WA+WB)-Q*DM)*AVG

      END FUNCTION RADLAYERMEAN

C     LENGTH-WEIGHTED MEAN OVER THE LEFT [WL,0] AND RIGHT [0,WR] HALF
C     CELLS (LENGTHS HL, HR) OF THE EVALUATION POINT.  EACH HALF CELL
C     HAS ITS OWN SLOPE D1L, D1R OF THE DENOMINATOR IN W (THE PRECESSION
C     FREQUENCY VARIES DIFFERENTLY TOWARDS EACH NEIGHBOUR).  NONFINITE
C     OR DEGENERATE INPUTS (E.G. THE X=0 ENERGY ENDPOINT) KEEP THE POINT
C     QUOTIENT FN/D0.
      PURE COMPLEX*16 FUNCTION RADLAYERCELL(FN,FS,D0,D1L,D1R,WL,WR,
     &                                      HL,HR,SREF)
      COMPLEX*16,INTENT(IN) :: FN,FS,D0
      REAL*8,INTENT(IN) :: D1L,D1R,WL,WR,HL,HR,SREF
      REAL*8 CHK

      CHK = ABS(DREAL(FN))+ABS(DIMAG(FN))+ABS(DREAL(FS))+
     &      ABS(DIMAG(FS))+ABS(DREAL(D0))+ABS(DIMAG(D0))+ABS(D1L)+
     &      ABS(D1R)
      IF (.NOT.(CHK.LE.HUGE(CHK)).OR.
     &    (D1L.EQ.0.0D0.AND.D1R.EQ.0.0D0).OR.HL+HR.LE.0.0D0) THEN
         RADLAYERCELL = FN/D0
         RETURN
      ENDIF
      RADLAYERCELL = (0.0D0,0.0D0)
      IF (HL.GT.0.0D0) RADLAYERCELL = RADLAYERCELL+
     &   HL*RADLAYERMEAN(FN,FS,D0,D1L,WL,0.0D0,SREF)
      IF (HR.GT.0.0D0) RADLAYERCELL = RADLAYERCELL+
     &   HR*RADLAYERMEAN(FN,FS,D0,D1R,0.0D0,WR,SREF)
      RADLAYERCELL = RADLAYERCELL/(HL+HR)

      END FUNCTION RADLAYERCELL

